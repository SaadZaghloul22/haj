/// Hajj and Umrah guide content (offline).
///
/// The rulings follow the well-known summary of Sheikh Ibn Baz, «التحقيق والإيضاح لكثير من مسائل
/// الحج والعمرة», as also published by the Saudi Ministry of Hajj guides. Every supplication carries
/// its source; sayings of the Companions are marked as such.
library;

enum Grade { rukn, wajib, sunnah, info }

extension GradeLabel on Grade {
  String get label => switch (this) {
        Grade.rukn => 'ركن',
        Grade.wajib => 'واجب',
        Grade.sunnah => 'سنة',
        Grade.info => 'تنبيه',
      };
}

class Dua {
  const Dua(this.title, this.text, this.source, {this.note, this.repeat = 1, this.quran = false});
  final String title;
  final String text;
  final String source;
  final String? note;
  final int repeat;
  final bool quran;
}

class GuideStep {
  const GuideStep({
    required this.id,
    required this.title,
    required this.when,
    required this.points,
    this.grade = Grade.sunnah,
    this.duas = const [],
    this.tip,
    this.counter,
  });

  final String id;
  final String title;

  /// Short line under the title: where/when.
  final String when;
  final List<String> points;
  final Grade grade;
  final List<Dua> duas;
  final String? tip;

  /// Opens the round counter ('tawaf' or 'sai').
  final String? counter;
}

class Guide {
  const Guide(this.id, this.title, this.subtitle, this.steps);
  final String id;
  final String title;
  final String subtitle;
  final List<GuideStep> steps;
}

